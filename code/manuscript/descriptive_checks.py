"""Further descriptive values reported in the manuscript: the volumetric ranking without the uncalibrated QUBIQ
floors, the consensus comparator on pixel floors and its image coverage, identical masks in seeded sources, gap
counts for the Cell Tracking Challenge leaderboard, C3RO residuals and the rater-bootstrap rule.

Reads results/; writes results/manuscript/values_checks.md.

    python code/manuscript/descriptive_checks.py
"""
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import kendalltau

ROOT = Path(__file__).resolve().parents[2]
R = ROOT / "results"
RM = R / "manuscript"
KEY = ["dataset", "task", "pair_class"]
rows = []


def put(key, value, source, note=""):
    rows.append((key, value, source, note))
    print(f"{key}: {value}")


tf = pd.read_csv(R / "layer" / "task_floor.csv")
typ = tf[tf.metric == "dice"][KEY + ["annotation_type", "n_raters"]].drop_duplicates(KEY)

# volumetric rank correlation without the QUBIQ floors (released without voxel spacing)
r3 = pd.read_csv(R / "r3_metric_reorder.csv")
vol = r3[r3.grid == "volumetric (mm)"]
put("B1.qubiq_in_volumetric_grid", vol[vol.dataset == "qubiq21"].task.tolist(), "results/r3_metric_reorder.csv")
calib = vol[vol.dataset != "qubiq21"]
rng = np.random.default_rng(20260903)
tau = kendalltau(calib.dice, calib["nsd@2"])[0]
bt = [kendalltau(k.dice, k["nsd@2"])[0] for k in (calib.sample(len(calib), replace=True,
      random_state=rng.integers(1 << 31)) for _ in range(2000))]
put("B1.tau_volumetric_without_qubiq", f"{tau:.2f} [{np.percentile(bt, 2.5):.2f}, {np.percentile(bt, 97.5):.2f}] "
    f"n={len(calib)}", "results/r3_metric_reorder.csv", "bootstrap over tasks, B=2000")
t95 = pd.read_csv(R / "tau95.csv")
put("B1.tau95_reached_rows", t95[t95.tau95.notna()][["dataset", "task", "unit", "tau95"]].values.tolist(),
    "results/tau95.csv")

# consensus comparator restricted to pixel floors, and its image coverage
s1 = pd.read_csv(R / "s1_e4_view_a_vs_b.csv").merge(typ, on=KEY, how="left")
ok = s1[s1.view_b_staple_dice.notna()]
put("B2.comparator_by_annotation_type", ok.annotation_type.value_counts().to_dict(), "results/s1_e4_view_a_vs_b.csv")
px = ok[ok.annotation_type == "pixel"]
for name, col in [("STAPLE", "delta_staple_dice"), ("majority", "delta_majority_dice")]:
    q = px[col].quantile([0.25, 0.5, 0.75]).round(3).tolist()
    put(f"B2.pixel_{name}", f"median {q[1]:.3f} (IQR {q[0]:.3f}-{q[2]:.3f}); higher on {int((px[col] > 0).sum())} of {len(px)}",
        "results/s1_e4_view_a_vs_b.csv", "pixel floors only")
pi = pd.read_csv(R / "layer" / "per_image.csv", usecols=KEY + ["image_id", "n_raters"])
elig = pi[pi.n_raters >= 3].groupby(KEY).image_id.nunique().rename("eligible").reset_index()
part = ok.merge(elig, on=KEY, how="left")
part = part[part.n_images_view_b < part.eligible]
put("B3.partial_comparator_floors", part[KEY + ["n_images_view_b", "eligible"]].values.tolist(),
    "results/s1_e4_view_a_vs_b.csv + per_image.csv")

# identical masks (Dice 1 and HD95 0) in seeded sources
pairs = pd.read_csv(R / "layer" / "pairs.csv", usecols=KEY + ["dice", "hd95"])
for ds in ["curvas", "pdacvi", "multiorg"]:
    p = pairs[pairs.dataset == ds]
    put(f"B4.identical_{ds}", f"{int(((p.dice == 1) & (p.hd95 == 0)).sum())} of {len(p)} pairs "
        f"(by task {p.groupby('task').size().to_dict()})", "results/layer/pairs.csv", "Dice 1 and HD95 0, any class")

# Cell Tracking Challenge adjacent gaps
ctc = pd.read_csv(R / "wp_l_ctc_per_dataset.csv")
det = ctc[ctc.measure == "DET"]
put("B5.ctc_det_gaps", f"all {int(det.n_adjacent_gaps.sum())} over {len(det)} datasets; spread>0 "
    f"{int(det[det.rss > 0].n_adjacent_gaps.sum())} over {int((det.rss > 0).sum())}", "results/wp_l_ctc_per_dataset.csv")
seg = ctc[ctc.measure == "SEG"]
put("B5.ctc_seg_gaps", f"{int(seg.n_adjacent_gaps.sum())} over {len(seg)} datasets; methods {seg.n_methods.min()}-"
    f"{seg.n_methods.max()}", "results/wp_l_ctc_per_dataset.csv")

# C3RO residuals under the source's definition
e5 = pd.read_csv(R / "e5_published_vs_recomputed.csv")
c3 = e5[e5.dataset == "c3ro"]
res = (c3.recomputed_source_definition - c3.published).round(6)
put("B6.c3ro_residuals", f"below {int((res < 0).sum())}, equal {int((res == 0).sum())}, above {int((res > 0).sum())}; "
    f"mean over all {res.mean():.4f}", "results/e5_published_vs_recomputed.csv")

# rater-bootstrap rule
rb = tf[(tf.ci_source == "rater_bootstrap") & (tf.metric == "dice") & tf.floor_reportable]
put("B7.rater_bootstrap_floors", f"{len(rb)}; images max {int(rb.n_images.max())}; raters min {int(rb.n_raters.min())}",
    "results/layer/task_floor.csv")

with (RM / "values_checks.md").open("w", encoding="utf-8") as f:
    f.write("# Further descriptive values (generated by code/manuscript/descriptive_checks.py)\n\n")
    f.write("| key | value | source | note |\n|---|---|---|---|\n")
    for k, v, s, n in rows:
        f.write(f"| {k} | {str(v).replace('|', '/')} | {s} | {n} |\n")
print(f"{len(rows)} entries -> {RM / 'values_checks.md'}")
